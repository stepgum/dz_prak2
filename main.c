#include <stdio.h>
#include <locale.h>

int main() {
    double X = 12, S = 150, L = 140;
    double W, D, C;

    setlocale(LC_ALL, "Russian");

    W = L / 100;
    D = S / W;
    C = X * D;

    printf("РАСЧЕТ СТОИМОСТИ ШЕЛКА ДЛЯ БРИГАНТИНЫ\n");
    printf("================================\n\n");
    printf("УСЛОВИЯ:\n");
    printf("- Стоимость погонного метра красного шелка: %.0f золотых.\n", X);
    printf("- Общая площадь парусов: %.0f м2.\n", S);
    printf("- Ширина ткани в рулоне: %.0f см.\n\n", L);
    printf("РАСЧЕТ:\n");
    printf("- Ширина ткани в метрах: %.0f см / 100 = %.2f м.\n", L, W);
    printf("- Длина ткани: %.0f м2 / %.2f м = %.4f м.\n", S, W, D);
    printf("- Стоимость: %.4f м * %.0f золотых/м = %.2f золотых.\n", D, X, C);
    printf("================================\n");
    printf("ГРЕЙ ЗАПЛАТИЛ ЗА ТКАНЬ: %.2f золотых\n", C);
    return 0;
}
